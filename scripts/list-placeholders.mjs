// Lists every open placeholder in the course data and writes claude/placeholder-register.md.
// Currently tracks: videoSlot blocks with no youtubeId. Add new placeholder kinds in `scan` below.
// Run: node scripts/list-placeholders.mjs
import fs from "node:fs";
import path from "node:path";

const DIR = "lib/content/data";
const rows = [];
let filled = 0;

function scan(course, unit, topic, lesson) {
  for (const b of lesson.blocks) {
    if (b.type === "videoSlot") {
      if (b.youtubeId) { filled++; continue; }
      rows.push({ course: course.title, slug: course.slug, unit: unit.title, topic: topic.title, lessonId: lesson.id, lesson: lesson.title, kind: "Video", title: b.title, minutes: b.minutes, brief: b.brief, watchFor: b.watchFor ?? [] });
    }
  }
}

for (const f of fs.readdirSync(DIR).filter((x) => x.endsWith(".json"))) {
  const course = JSON.parse(fs.readFileSync(path.join(DIR, f), "utf8"));
  for (const unit of course.units) for (const topic of unit.topics) for (const lesson of topic.lessons) scan(course, unit, topic, lesson);
}

const today = new Date().toLocaleDateString("en-CA", { timeZone: "Australia/Perth" });
let md = `# Placeholder Register

Generated by \`node scripts/list-placeholders.mjs\` on ${today}. Do not edit by hand: fill the placeholder, then re-run the script.

**Open: ${rows.length}** · Filled: ${filled}

## How to fill a video placeholder

1. Pick a video that matches the brief and "watch for" points. Check it plays, is school-appropriate and is embeddable.
2. Run \`node scripts/set-video.mjs <lessonId> <youtubeId>\` (the ID is the part after \`v=\` in the YouTube URL).
3. Re-run \`node scripts/list-placeholders.mjs\` to refresh this register, then commit.

Until an ID is set, students see a clearly labelled "Video coming soon" card, so nothing is broken.

`;
const groups = {};
for (const r of rows) (groups[`${r.course} / ${r.unit} / ${r.topic}`] ??= []).push(r);
for (const [g, items] of Object.entries(groups)) {
  md += `## ${g}\n\n`;
  for (const r of items) {
    md += `### ${r.lesson}\n- Lesson ID: \`${r.lessonId}\`\n- Type: ${r.kind}: "${r.title}"${r.minutes ? ` (about ${r.minutes} min)` : ""}\n- Brief: ${r.brief}\n- Watch for: ${r.watchFor.join("; ") || "n/a"}\n- Status: OPEN\n\n`;
  }
}
fs.writeFileSync("claude/placeholder-register.md", md);
console.log(`Open placeholders: ${rows.length}, filled: ${filled}. Wrote claude/placeholder-register.md`);
